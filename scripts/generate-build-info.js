const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

let commitHash = 'dev';
let commitCount = '1';
let commitDate = new Date().toISOString().split('T')[0];

try {
  commitHash = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
} catch (e) {
  if (process.env.GITHUB_SHA) {
    commitHash = process.env.GITHUB_SHA.substring(0, 7);
  }
}

try {
  commitCount = execSync('git rev-list --count HEAD', { encoding: 'utf8' }).trim();
} catch (e) {
  if (process.env.GITHUB_RUN_NUMBER) {
    commitCount = process.env.GITHUB_RUN_NUMBER;
  }
}

try {
  commitDate = execSync('git log -1 --format=%cd --date=short', { encoding: 'utf8' }).trim();
} catch (e) {}

let appVersion = '1.0.0';
try {
  const appJson = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'app.json'), 'utf8'));
  appVersion = appJson.expo?.version || '1.0.0';
} catch (e) {}

const content = `// This file is auto-generated by scripts/generate-build-info.js
// Do not edit manually.

export interface BuildInfo {
  version: string;
  commitHash: string;
  commitCount: number;
  commitDate: string;
}

export const BUILD_INFO: BuildInfo = {
  version: '${appVersion}',
  commitHash: '${commitHash}',
  commitCount: ${parseInt(commitCount, 10) || 1},
  commitDate: '${commitDate}'
};
`;

const targetDir = path.join(__dirname, '..', 'src', 'constants');
if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

fs.writeFileSync(path.join(targetDir, 'buildInfo.ts'), content, 'utf8');
console.log(`[build-info] Generated src/constants/buildInfo.ts: Commit ${commitHash} (#${commitCount})`);
